"""Build the self-hosted browser runtime (PRD FR-L3, FR-L7; plan T5.2).

Writes into web/public/ (git-ignored, regenerated by `make web-runtime`):

* pyodide/   the pinned Pyodide distribution, copied from the npm package, plus the
             numpy wheel. The wheel is the only file fetched from the network; it is
             checked against the sha256 in Pyodide's own pyodide-lock.json before it is
             written (and Pyodide checks it again when loading).
* py/hpfold.zip   the core package (src/hpfold/**/*.py only), deterministic: sorted
             entries, fixed timestamps, Unix attributes and no compression (so the bytes
             do not depend on the OS or the zlib build).
* py/manifest.json   versions and the zip's sha256.

Trust: the numpy wheel must match BOTH the sha256 in pyodide-lock.json (from the npm
tarball, so use `npm ci`) and the hash pinned below. Everything is built in a staging
directory and swapped in at the end: a failed build leaves the previous runtime untouched,
and a rebuild leaves no stale files (for example an old wheel after a version bump).

Self-hosting means the page works offline after the first visit and always runs exactly
the code and versions the paper used.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import shutil
import urllib.request
import zipfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
PYODIDE_VERSION = "0.28.3"
PYODIDE_FILES = ("pyodide.mjs", "pyodide.asm.js", "pyodide.asm.wasm", "python_stdlib.zip",
                 "pyodide-lock.json")
NUMPY_SHA256 = "3db3c4f3e0448f4d62a85c262692f1260ccd8a91335442bd2442f21ffeddb558"  # numpy 2.2.5
CDN = f"https://cdn.jsdelivr.net/pyodide/v{PYODIDE_VERSION}/full/"
MAX_DOWNLOAD_BYTES = 64 * 1024 * 1024  # the numpy wheel is about 3 MB
STAGING = ".runtime-staging"
RUNTIME_DIRS = ("pyodide", "py")
WHEEL_NAME = re.compile(r"[A-Za-z0-9_.+-]+\.whl")
ZIP_DATE = (1980, 1, 1, 0, 0, 0)
DOWNLOAD_TIMEOUT_S = 120

FetchFn = Callable[[str], bytes]


def _download(url: str) -> bytes:
    if not url.startswith(CDN):
        raise ValueError("refusing to download from outside the pinned Pyodide CDN")
    # the https CDN prefix is checked above; the sha256 check after download covers redirects
    with urllib.request.urlopen(url, timeout=DOWNLOAD_TIMEOUT_S) as response:  # nosec B310
        data = response.read(MAX_DOWNLOAD_BYTES + 1)
    if len(data) > MAX_DOWNLOAD_BYTES:
        raise ValueError("download too large: refusing it")
    return data


def check_pyodide(pyodide_dir: Path) -> None:
    meta = json.loads((Path(pyodide_dir) / "package.json").read_text(encoding="utf-8"))
    if meta.get("version") != PYODIDE_VERSION:
        raise RuntimeError(f"expected Pyodide {PYODIDE_VERSION} in {pyodide_dir}, "
                           f"found {meta.get('version')}; run npm --prefix web ci")


def copy_pyodide(pyodide_dir: Path, dest: Path) -> None:
    src = Path(pyodide_dir)
    missing = [name for name in PYODIDE_FILES if not (src / name).is_file()]
    if missing:
        raise FileNotFoundError(f"Pyodide distribution incomplete, missing: {', '.join(missing)}")
    dest.mkdir(parents=True, exist_ok=True)
    for name in PYODIDE_FILES:
        shutil.copyfile(src / name, dest / name)


def wheel_url(file_name: str) -> str:
    if not WHEEL_NAME.fullmatch(file_name) or ".." in file_name:
        raise ValueError("unexpected wheel file name in pyodide-lock.json")
    return CDN + file_name


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def fetch_wheel(entry: dict[str, Any], dest_dir: Path, fetch: FetchFn = _download,
                wheel_dir: Path | None = None) -> Path:
    """Place the verified wheel in dest_dir; reuses a verified copy already there."""
    name = entry["file_name"]
    url = wheel_url(name)
    expected = entry["sha256"]
    dest = Path(dest_dir) / name
    if dest.is_file() and _sha256(dest.read_bytes()) == expected:
        return dest
    data = (Path(wheel_dir) / name).read_bytes() if wheel_dir is not None else fetch(url)
    if _sha256(data) != expected:
        raise ValueError(f"sha256 mismatch for {name}: not writing it")
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)
    return dest


def build_hpfold_zip(src_dir: Path, out_path: Path) -> bytes:
    """Deterministic zip of src_dir/hpfold/**/*.py; returns the bytes written."""
    base = Path(src_dir)
    files = sorted(
        (p for p in (base / "hpfold").rglob("*.py") if "__pycache__" not in p.parts),
        key=lambda p: p.relative_to(base).as_posix(),
    )
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_STORED) as archive:
        for path in files:
            info = zipfile.ZipInfo(path.relative_to(base).as_posix(), date_time=ZIP_DATE)
            info.compress_type = zipfile.ZIP_STORED
            info.create_system = 3  # Unix, on every OS
            info.external_attr = 0o644 << 16
            archive.writestr(info, path.read_bytes())
    data = buffer.getvalue()
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(data)
    return data


def build(pyodide_dir: Path = ROOT / "web" / "node_modules" / "pyodide", src_dir: Path = ROOT / "src",
          out_dir: Path = ROOT / "web" / "public", fetch: FetchFn = _download,
          wheel_dir: Path | None = None, pinned_sha256: str = NUMPY_SHA256) -> dict[str, str]:
    pyodide_dir, out_dir = Path(pyodide_dir), Path(out_dir)
    check_pyodide(pyodide_dir)
    lock = json.loads((pyodide_dir / "pyodide-lock.json").read_text(encoding="utf-8"))
    numpy = lock["packages"]["numpy"]
    if numpy["sha256"] != pinned_sha256:
        raise ValueError("numpy sha256 in pyodide-lock.json differs from the pinned hash")

    stage = out_dir / STAGING
    shutil.rmtree(stage, ignore_errors=True)
    try:
        previous = out_dir / "pyodide" / numpy["file_name"]
        if wheel_dir is None and previous.is_file() and _sha256(previous.read_bytes()) == numpy["sha256"]:
            wheel_dir = previous.parent  # reuse the verified wheel from the last build
        fetch_wheel(numpy, stage / "pyodide", fetch=fetch, wheel_dir=wheel_dir)  # verify first
        copy_pyodide(pyodide_dir, stage / "pyodide")
        zip_bytes = build_hpfold_zip(src_dir, stage / "py" / "hpfold.zip")
        manifest = {"pyodide": PYODIDE_VERSION, "numpy": numpy["version"],
                    "numpy_wheel": numpy["file_name"], "hpfold_sha256": _sha256(zip_bytes)}
        (stage / "py" / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n",
                                                    encoding="utf-8")
        for name in RUNTIME_DIRS:  # swap in only after everything above succeeded
            shutil.rmtree(out_dir / name, ignore_errors=True)
            (stage / name).rename(out_dir / name)
    finally:
        shutil.rmtree(stage, ignore_errors=True)
    return manifest


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--pyodide-dir", type=Path, default=ROOT / "web" / "node_modules" / "pyodide")
    parser.add_argument("--out", type=Path, default=ROOT / "web" / "public")
    parser.add_argument("--wheel-dir", type=Path, default=None,
                        help="use a local copy of the numpy wheel instead of downloading it")
    args = parser.parse_args(argv)
    manifest = build(pyodide_dir=args.pyodide_dir, out_dir=args.out, wheel_dir=args.wheel_dir)
    print(json.dumps(manifest))


if __name__ == "__main__":  # pragma: no cover
    main()
